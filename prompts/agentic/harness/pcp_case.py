#!/usr/bin/env python3
"""PCP case runner — interprets `pcp-case/v0` TOML cases (see JOURNAL.md §7).

usage: pcp_case.py [--checks-only] [--dry-run] <tests/case-NNN-name>

Flow:
  1. parse <case-dir>/case.toml
  2. generate a guest script (workspace setup, pi invocation, artifact capture)
  3. delegate the VM run to sandbox/run-test.sh (via PCP_GUEST_SCRIPT hook)
  4. run the case's checks on the HOST against collected artifacts
  5. write results/checks.json + results/verdict.txt

--checks-only: skip steps 2-3, run checks against existing artifacts.
--dry-run:     print the parsed case + generated guest script, do not run.

Check contract: shell snippet run with cwd = case results dir.
Env: PCP_ARTIFACTS (…/results/artifacts), PCP_CASE_DIR, PCP_CASE,
     PCP_INGUEST (helper to run a command inside a throwaway guest container).
Exit 0 = pass. `type = "manual"` checks are recorded but never fail the case.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tempfile
import time
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN_TEST = os.path.join(ROOT, "sandbox", "run-test.sh")
IN_GUEST = os.path.join(ROOT, "harness", "in-guest.sh")

GUEST_TEMPLATE = """#!/bin/bash
# Generated by harness/pcp_case.py from case.toml — do not edit.
set -uo pipefail

WS=/tmp/workspace
mkdir -p "$WS"
if [ -d /work/fixture ]; then cp -a /work/fixture/. "$WS"/; fi
cd "$WS"
{setup}
SETUP_RC=$?
if [ "$SETUP_RC" -ne 0 ]; then
  echo "pcp: setup failed (rc=$SETUP_RC)"
  exit "$SETUP_RC"
fi
RC=0
{agent_block}
# ---- artifact capture (generous + fixed; see JOURNAL.md §7.2) ----
mkdir -p /results/artifacts/workspace
cp -a "$WS"/. /results/artifacts/workspace/ 2>/dev/null
# keep artifacts lean; heavy build dirs are re-creatable by checks
rm -rf /results/artifacts/workspace/target /results/artifacts/workspace/node_modules
find /results/artifacts/workspace -name __pycache__ -type d -exec rm -rf {{}} + 2>/dev/null
if [ -d /home/agent/.pi/agent/sessions ]; then
  cp -a /home/agent/.pi/agent/sessions /results/artifacts/sessions
fi
exit $RC
"""

AGENT_BLOCK = """if [ -f /pcp-run/prompt.txt ]; then
  pi --mode json -p "$(cat /pcp-run/prompt.txt)" \\
     > /results/artifacts/pi-output.json 2> /results/artifacts/pi-stderr.log
  RC=$?
  echo "pcp: pi exited rc=$RC"
else
  echo "pcp: no prompt (case misconfigured?)" >&2
  RC=1
fi"""


def fail(msg: str, code: int = 2) -> None:
    print(f"pcp_case: {msg}", file=sys.stderr)
    sys.exit(code)


def indent(text: str, pad: str = "") -> str:
    return "\n".join(pad + line if line else "" for line in text.splitlines())


def load_case(case_dir: str) -> dict:
    path = os.path.join(case_dir, "case.toml")
    if not os.path.isfile(path):
        fail(f"no case.toml in {case_dir}")
    with open(path, "rb") as f:
        case = tomllib.load(f)
    if not str(case.get("schema", "")).startswith("pcp-case/"):
        fail(f"{path}: schema must be pcp-case/vN, got {case.get('schema')!r}")
    if not case.get("name"):
        fail(f"{path}: missing 'name'")
    if not case.get("no_agent") and not case.get("prompt"):
        fail(f"{path}: agent cases need 'prompt'")
    return case


def make_guest_script(case: dict) -> str:
    setup = indent(case.get("setup", "true"))
    agent_block = "" if case.get("no_agent") else indent(AGENT_BLOCK)
    return GUEST_TEMPLATE.format(setup=setup, agent_block=agent_block)


def run_vm(case: dict, case_dir: str, results: str) -> int:
    rundir = tempfile.mkdtemp(prefix="pcp-run-")
    with open(os.path.join(rundir, "guest-run.sh"), "w") as f:
        f.write(make_guest_script(case))
    os.chmod(os.path.join(rundir, "guest-run.sh"), 0o755)
    if case.get("prompt"):
        with open(os.path.join(rundir, "prompt.txt"), "w") as f:
            f.write(case["prompt"])
    env = dict(os.environ, PCP_GUEST_SCRIPT=os.path.join(rundir, "guest-run.sh"))
    print(f"pcp_case: running VM for {case['name']} …")
    proc = subprocess.run(["bash", RUN_TEST, case_dir], env=env)
    return proc.returncode


def run_checks(case: dict, case_dir: str, results: str, artifacts: str) -> list[dict]:
    os.makedirs(artifacts, exist_ok=True)
    env_common = dict(
        os.environ,
        PCP_ARTIFACTS=artifacts,
        PCP_CASE_DIR=case_dir,
        PCP_CASE=case["name"],
        PCP_INGUEST=IN_GUEST,
    )
    out = []
    for i, chk in enumerate(case.get("checks", [])):
        name, run = chk.get("name"), chk.get("run")
        ctype = chk.get("type", "check")
        if not name or run is None:
            fail(f"checks[{i}]: needs 'name' and 'run'")
        t0 = time.monotonic()
        proc = subprocess.run(
            ["bash", "-c", run], cwd=results, env=env_common,
            capture_output=True, text=True, timeout=chk.get("timeout", 600),
        )
        dt = int((time.monotonic() - t0) * 1000)
        if ctype == "manual":
            status = "manual"
        elif proc.returncode == 0:
            status = "pass"
        else:
            status = "fail"
        entry = {
            "name": name, "type": ctype, "status": status,
            "exitCode": proc.returncode, "durationMs": dt,
            "stdout": proc.stdout[-4000:], "stderr": proc.stderr[-2000:],
        }
        out.append(entry)
        print(f"pcp_case: check {name:<28} {status:<7} rc={proc.returncode} ({dt} ms)")
    return out


def write_results(case: dict, results: str, checks: list[dict]) -> int:
    with open(os.path.join(results, "checks.json"), "w") as f:
        json.dump(
            {"schema": case["schema"], "case": case["name"],
             "generatedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
             "checks": checks},
            f, indent=2,
        )
    mechanical = [c for c in checks if c["type"] != "manual"]
    if any(c["status"] == "fail" for c in mechanical):
        verdict = "FAIL"
    elif mechanical and all(c["status"] == "pass" for c in mechanical):
        verdict = "PASS"
    else:
        verdict = "MANUAL"  # nothing mechanical to score (or checks-only, empty)
    with open(os.path.join(results, "verdict.txt"), "w") as f:
        f.write(verdict + "\n")
    print(f"pcp_case: verdict {verdict} ({len(checks)} checks) → {results}")
    return 0 if verdict in ("PASS", "MANUAL") else 1


def main() -> None:
    args = sys.argv[1:]
    checks_only = "--checks-only" in args
    dry_run = "--dry-run" in args
    args = [a for a in args if not a.startswith("--")]
    if len(args) != 1:
        fail("usage: run-case.sh [--checks-only] [--dry-run] <tests/case-NNN-name>")
    case_dir = os.path.abspath(args[0])
    case = load_case(case_dir)
    results = os.path.join(case_dir, "results")
    artifacts = os.path.join(results, "artifacts")
    os.makedirs(results, exist_ok=True)

    if dry_run:
        print(f"--- case: {case['name']} ({case['schema']}) ---")
        print(f"no_agent={case.get('no_agent', False)}  "
              f"fixture={'fixture' if os.path.isdir(os.path.join(case_dir, 'fixture')) else None}")
        print("--- guest script ---")
        print(make_guest_script(case))
        print("--- checks ---")
        for c in case.get("checks", []):
            print(f"[{c.get('type', 'check')}] {c['name']}")
        return

    run_rc = None
    if not checks_only:
        run_rc = run_vm(case, case_dir, results)
        print(f"pcp_case: VM run exit={run_rc}")

    checks = run_checks(case, case_dir, results, artifacts)
    rc = write_results(case, results, checks)
    if run_rc is not None and run_rc != 0:
        print(f"pcp_case: note — VM run exited nonzero ({run_rc}); "
              f"see results/metadata.json", file=sys.stderr)
    sys.exit(rc)


if __name__ == "__main__":
    main()
